"""
Unit Tests for SQLite Hardening & Single-Writer Ingestion Queue
Milestone M1.3 & M1.4 Verification
"""

import unittest
import os
import sys
import tempfile
import threading
import sqlite3
import time

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if BASE_DIR not in sys.path:
    sys.path.insert(0, BASE_DIR)

from database.schema_manager import SchemaManager
from database.sqlite_queue import SingleWriterQueue, QueueFullError
from models.canonical_model import CanonicalObject, CanonicalField

class TestDatabaseAndQueue(unittest.TestCase):

    def setUp(self):
        self.temp_dir = tempfile.mkdtemp()
        self.db_path = os.path.join(self.temp_dir, "test_bw_studio.sqlite")
        self.schema_mgr = SchemaManager(self.db_path)
        self.schema_mgr.apply_migrations()

    def tearDown(self):
        if os.path.exists(self.db_path):
            try:
                os.remove(self.db_path)
            except Exception:
                pass
        try:
            os.rmdir(self.temp_dir)
        except Exception:
            pass

    def test_wal_configuration_and_integrity(self):
        conn = self.schema_mgr.get_connection()
        cur = conn.cursor()
        cur.execute("PRAGMA journal_mode;")
        mode = cur.fetchone()[0]
        self.assertEqual(mode.lower(), "wal")
        conn.close()

        integrity = self.schema_mgr.verify_integrity()
        self.assertEqual(integrity["status"], "PASSED")
        self.assertEqual(integrity["messages"], ["ok"])

    def test_single_writer_basic_ingestion(self):
        queue = SingleWriterQueue(self.db_path, batch_size=10, flush_interval_sec=0.02)
        queue.start()

        obj = CanonicalObject(
            urn="urn:sap:bw:s21:200:adso:ZTEST_01:A",
            description="Test ADSO 01",
            infoarea="FIN_ANALYTICS"
        )
        queue.enqueue_object(obj.to_canonical_dict())

        # Give writer time to flush
        time.sleep(0.1)
        queue.stop(timeout=5.0)

        conn = sqlite3.connect(self.db_path)
        cur = conn.cursor()
        cur.execute("SELECT urn, description, content_fingerprint FROM canonical_bw_objects WHERE urn = ?", (obj.urn.versioned_urn,))
        row = cur.fetchone()
        conn.close()

        self.assertIsNotNone(row)
        self.assertEqual(row[0], "urn:sap:bw:s21:200:adso:ZTEST_01:A")
        self.assertEqual(row[1], "Test ADSO 01")
        self.assertEqual(row[2], obj.content_fingerprint)

    def test_concurrent_producers_no_sqlite_lock(self):
        # 5 worker threads concurrently enqueuing 40 objects each = 200 objects
        queue = SingleWriterQueue(self.db_path, batch_size=25, flush_interval_sec=0.01)
        queue.start()

        errors = []

        def worker_task(worker_id):
            try:
                for i in range(40):
                    tech_name = f"ZTEST_W{worker_id}_{i}"
                    obj = CanonicalObject(
                        urn=f"urn:sap:bw:s21:200:adso:{tech_name}:A",
                        description=f"Generated by worker {worker_id} item {i}"
                    )
                    queue.enqueue_object(obj.to_canonical_dict())
            except Exception as e:
                errors.append(e)

        threads = [threading.Thread(target=worker_task, args=(w,)) for w in range(5)]
        for t in threads:
            t.start()
        for t in threads:
            t.join()

        self.assertEqual(len(errors), 0, f"Producer thread errors: {errors}")

        queue.stop(timeout=10.0)

        conn = sqlite3.connect(self.db_path)
        cur = conn.cursor()
        cur.execute("SELECT COUNT(*) FROM canonical_bw_objects WHERE technical_name LIKE 'ZTEST_W%'")
        count = cur.fetchone()[0]
        conn.close()

        self.assertEqual(count, 200)

    def test_backpressure_queue_full(self):
        # Bounded queue with maxsize=5
        queue = SingleWriterQueue(self.db_path, maxsize=5, batch_size=10)
        # Note: we do NOT start the writer thread so the buffer fills up immediately
        for i in range(5):
            obj = CanonicalObject(urn=f"urn:sap:bw:s21:200:adso:ZBP_{i}:A")
            queue.enqueue_object(obj.to_canonical_dict(), block=False)

        # 6th item must raise QueueFullError
        obj_overflow = CanonicalObject(urn="urn:sap:bw:s21:200:adso:ZBP_OVERFLOW:A")
        with self.assertRaises(QueueFullError):
            queue.enqueue_object(obj_overflow.to_canonical_dict(), block=False)

    def test_upsert_idempotency(self):
        queue = SingleWriterQueue(self.db_path, batch_size=10, flush_interval_sec=0.01)
        queue.start()

        obj_v1 = CanonicalObject(
            urn="urn:sap:bw:s21:200:adso:ZIDEM_01:A",
            description="Initial Description"
        )
        queue.enqueue_object(obj_v1.to_canonical_dict())
        time.sleep(0.05)

        obj_v2 = CanonicalObject(
            urn="urn:sap:bw:s21:200:adso:ZIDEM_01:A",
            description="Updated Description"
        )
        queue.enqueue_object(obj_v2.to_canonical_dict())
        time.sleep(0.05)

        queue.stop(timeout=5.0)

        conn = sqlite3.connect(self.db_path)
        cur = conn.cursor()
        cur.execute("SELECT description, content_fingerprint FROM canonical_bw_objects WHERE technical_name = 'ZIDEM_01'")
        rows = cur.fetchall()
        conn.close()

        self.assertEqual(len(rows), 1, "Upsert must update in place without duplicate records")
        self.assertEqual(rows[0][0], "Updated Description")

    def test_checkpoint_and_integrity_check(self):
        queue = SingleWriterQueue(self.db_path)
        self.assertTrue(queue.verify_integrity())
        ckpt = queue.checkpoint("TRUNCATE")
        self.assertEqual(ckpt["mode"], "TRUNCATE")
        self.assertIn("busy", ckpt)

    def test_dlq_and_item_isolation(self):
        # Condition C-01: A batch containing a corrupted item must isolate the corrupt item to DLQ
        # while successfully committing valid items in the batch.
        queue = SingleWriterQueue(self.db_path, batch_size=5, flush_interval_sec=0.01)
        queue.start()

        valid_obj1 = CanonicalObject(urn="urn:sap:bw:s21:200:adso:ZVALID_01:A", description="Valid 01")
        corrupt_obj = {"urn": "urn:sap:bw:s21:200:adso:ZCORRUPT:A"} # Missing stable_urn, system_id, etc.
        valid_obj2 = CanonicalObject(urn="urn:sap:bw:s21:200:adso:ZVALID_02:A", description="Valid 02")

        queue.enqueue_object(valid_obj1.to_canonical_dict())
        queue.enqueue_object(corrupt_obj) # Will trigger KeyError in _upsert_object
        queue.enqueue_object(valid_obj2.to_canonical_dict())

        time.sleep(0.15)
        queue.stop(timeout=5.0)

        # Verify DLQ received the corrupt item
        self.assertEqual(queue.dlq_count, 1)
        dlq_entries = queue.get_dlq()
        self.assertEqual(len(dlq_entries), 1)
        self.assertIn("KeyError", dlq_entries[0]["error_type"])

        # Verify valid objects were committed despite the corrupt item in the batch
        conn = sqlite3.connect(self.db_path)
        cur = conn.cursor()
        cur.execute("SELECT technical_name FROM canonical_bw_objects WHERE technical_name IN ('ZVALID_01', 'ZVALID_02')")
        rows = [r[0] for r in cur.fetchall()]
        conn.close()

        self.assertIn("ZVALID_01", rows)
        self.assertIn("ZVALID_02", rows)

    def test_execute_write_synchronous_and_failure(self):
        # Condition C-02: SingleWriterQueue arbitrary SQL write execution
        queue = SingleWriterQueue(self.db_path, batch_size=5, flush_interval_sec=0.01)
        queue.start()

        # Create a test table via execute_write
        queue.execute_write("CREATE TABLE IF NOT EXISTS test_sql_write (id INTEGER PRIMARY KEY, note TEXT);")
        queue.execute_write("INSERT INTO test_sql_write (id, note) VALUES (?, ?);", (1, "Test Note"))

        conn = sqlite3.connect(self.db_path)
        cur = conn.cursor()
        cur.execute("SELECT note FROM test_sql_write WHERE id = 1")
        row = cur.fetchone()
        conn.close()

        self.assertIsNotNone(row)
        self.assertEqual(row[0], "Test Note")

        queue.stop(timeout=5.0)

if __name__ == "__main__":
    unittest.main()
